# Useful shortcuts that can speed up your development when using Visual Studio. 


# Navigating through Code

# Goes to the definition of the function or method you have selected. You can also use this on namespaces to look at the source code of them. 
# To use this shortcut you must either click or fully highlight the text you wish to go to then hit F12 otherwise it won't work. 
Go to Definition - F12 


Go to Declaration/Implementation - Ctrl + F12 # 